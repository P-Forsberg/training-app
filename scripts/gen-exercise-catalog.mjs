// Generates the global exercise catalog in two places from one source:
//   - src/data/exerciseCatalog.generated.ts (bundled, so import works offline before first sync)
//   - supabase/migrations/20260923000003_exercise_catalog.sql (global rows, owner is null)
// IDs are deterministic (name-based UUIDv5-style) so both sides always agree.
// Usage: node scripts/gen-exercise-catalog.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const NAMESPACE = 'training-app/exercise/';
const source = JSON.parse(readFileSync(new URL('./exercise-catalog.source.json', import.meta.url), 'utf8'));

function uuidFromName(name) {
  const h = createHash('sha1').update(NAMESPACE + name).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const hex = h.subarray(0, 16).toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const rows = source.map((e) => ({
  id: uuidFromName(e.name),
  canonicalName: e.name,
  aliases: e.aliases,
  category: e.category,
  movementPattern: e.pattern,
  isBarbell: e.barbell,
}));

const ts = `// Generated by scripts/gen-exercise-catalog.mjs. Do not edit by hand.
export interface CatalogExercise {
  id: string;
  canonicalName: string;
  aliases: string[];
  category: string;
  movementPattern: string;
  isBarbell: boolean;
}

export const EXERCISE_CATALOG: CatalogExercise[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL('../src/data/exerciseCatalog.generated.ts', import.meta.url), ts);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const values = rows
  .map((r) => `  (${q(r.id)}, null, ${q(r.canonicalName)}, ${arr(r.aliases)}, ${q(r.category)}, ${q(r.movementPattern)}, ${r.isBarbell})`)
  .join(',\n');

const sql = `-- Generated by scripts/gen-exercise-catalog.mjs. Do not edit by hand.
-- Global exercise catalog (owner is null), readable by every signed-in user.

insert into public.exercises (id, owner, canonical_name, aliases, category, movement_pattern, is_barbell)
values
${values}
on conflict (id) do update set
  canonical_name = excluded.canonical_name,
  aliases = excluded.aliases,
  category = excluded.category,
  movement_pattern = excluded.movement_pattern,
  is_barbell = excluded.is_barbell,
  updated_at = now();
`;
writeFileSync(new URL('../supabase/migrations/20260923000003_exercise_catalog.sql', import.meta.url), sql);

console.log(`Wrote ${rows.length} exercises.`);
